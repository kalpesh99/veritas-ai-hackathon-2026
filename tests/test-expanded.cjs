const assert=require('node:assert/strict');
const {topics,search}=require('../concern-catalog.js');
const original=require('../evaluation/catalog-v1.json');
const manifest=require('../evaluation/catalog-v2.json');
const fixtures=require('../expanded-fixtures.js');
const report=require('../evaluation/expanded-results.json');
let n=0;const check=f=>{f();n++;};
check(()=>assert.equal(topics.length,24));
check(()=>assert.equal(new Set(topics.map(t=>t.id)).size,24));
check(()=>assert.equal(topics.reduce((n,t)=>n+t.aliases.length,0),168));
check(()=>assert.equal(manifest.aliasCount,168));
check(()=>assert.deepEqual(manifest.topics,topics));
check(()=>assert.ok(topics.every(t=>t.sourceChecked&&t.sourceOrganization&&t.question&&t.followup)));
check(()=>assert.ok(topics.every(t=>new URL(t.url).protocol==='https:'&&['medlineplus.gov','www.niddk.nih.gov','www.cdc.gov'].includes(new URL(t.url).hostname))));
check(()=>assert.ok(original.every(t=>topics.find(x=>x.id===t.id).text===t.text)));
check(()=>assert.equal(fixtures.cases.length,60));
check(()=>assert.equal(fixtures.cases.filter(x=>x[1]).length,48));
check(()=>assert.equal(fixtures.cases.filter(x=>!x[1]).length,12));
check(()=>assert.ok(topics.every(t=>fixtures.cases.filter(x=>x[1]===t.id).length===2)));
check(()=>assert.equal(search('').length,24));
check(()=>assert.ok(search('pins and needles').some(t=>t.id==='tingling')));
check(()=>assert.ok(search('tummy ache').some(t=>t.id==='digestion')));
check(()=>assert.ok(search('dizzyness').some(t=>t.id==='dizziness')));
check(()=>assert.ok(search('headace').some(t=>t.id==='headache')));
check(()=>assert.ok(search('medecine').some(t=>t.id==='medicines')));
check(()=>assert.ok(search('knees ache').some(t=>t.id==='joints')));
check(()=>assert.deepEqual(search('laptop password'),[]));
check(()=>assert.deepEqual(search('constructor __proto__'),[]));
check(()=>assert.ok(topics.every(t=>t.aliases.every(a=>search(a).some(x=>x.id===t.id)))));
check(()=>assert.deepEqual(report.rows.map(r=>[r.query,r.expected]),fixtures.cases));
check(()=>assert.equal(report.catalogVersion,manifest.version));
check(()=>assert.equal(report.threshold,fixtures.threshold));
check(()=>assert.equal(report.top1Correct,report.rows.filter(r=>r.expected&&r.top1===r.expected).length));
check(()=>assert.equal(report.top3ContainsTarget,report.rows.filter(r=>r.expected&&r.offered.includes(r.expected)).length));
check(()=>assert.equal(report.ambiguousOrUnrelatedWithheld,report.rows.filter(r=>!r.expected&&!r.offered.length).length));
check(()=>assert.equal(report.lexicalTop1Correct,fixtures.cases.filter(([q,id])=>id&&fixtures.lexical(q,topics)[0]?.id===id).length));
console.log(n+' expanded-catalog provenance, search and fixture checks passed. These are engineering checks, not medical validation.');
