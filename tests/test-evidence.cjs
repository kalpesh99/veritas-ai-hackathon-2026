const assert=require('node:assert/strict');
const {summarize}=require('../concern-evidence.js');
const r=require('../evaluation/semantic-results.json');
const before=JSON.stringify(r),m=summarize(r);
assert.equal(m.supported,18);
assert.equal(m.missedTargets,1);
assert.equal(m.queriesWithExtraTopics,5);
assert.equal(m.extraTopicSuggestions,6);
assert.equal(m.unrelatedOrVagueWithSuggestions,0);
assert.equal(m.unrelatedOrVague,7);
assert.equal(m.totalSuggestions,23);
assert.equal(m.perTopic.reduce((n,r)=>n+r.missed,0),m.missedTargets);
assert.equal(m.perTopic.reduce((n,r)=>n+r.nonTargetOffers,0),m.extraTopicSuggestions);
assert.equal(JSON.stringify(r),before);
const synthetic=summarize({rows:[{expected:'a',offered:['b']},{expected:null,offered:['a']},{expected:'b',offered:[]}]});
assert.equal(synthetic.missedTargets,2);
assert.equal(synthetic.unrelatedOrVagueWithSuggestions,1);
assert.equal(synthetic.extraTopicSuggestions,1);
console.log('13 recorded-evidence counting and non-mutation checks passed.');
